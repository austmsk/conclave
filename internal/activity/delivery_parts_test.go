func run(id int64, name, status, conclusion, app string) github.CheckRun {
	return github.CheckRun{ID: id, Name: name, Status: status, Conclusion: conclusion, AppSlug: app}
}

// TestEvaluateChecks: one case per rule of the CI verdict.
func TestEvaluateChecks(t *testing.T) {
	p := gate.CIPolicy{RequiredChecks: []string{"build", "test"}, CheckApp: "github-actions"}
	const gha = "github-actions"
	cases := []struct {
		name            string
		runs            []github.CheckRun
		completed, pass bool
	}{
		{"no runs yet", nil, false, false},
		{"one still running", []github.CheckRun{run(1, "build", "completed", "success", gha), run(2, "test", "in_progress", "", gha)}, false, false},
		{"both passed", []github.CheckRun{run(1, "build", "completed", "success", gha), run(2, "test", "completed", "success", gha)}, true, true},
		{"skipped and neutral pass", []github.CheckRun{run(1, "build", "completed", "skipped", gha), run(2, "test", "completed", "neutral", gha)}, true, true},
		{"a failure fails at once", []github.CheckRun{run(1, "build", "completed", "failure", gha), run(2, "test", "queued", "", gha)}, true, false},
		{"cancelled fails", []github.CheckRun{run(1, "build", "completed", "cancelled", gha), run(2, "test", "completed", "success", gha)}, true, false},
		{"a re-run supersedes the failure", []github.CheckRun{
			run(1, "build", "completed", "failure", gha), run(3, "build", "completed", "success", gha), run(2, "test", "completed", "success", gha),
		}, true, true},
		// The attack: another App with checks:write reports the required
		// names as passed. Its runs do not count.
		{"another App cannot satisfy a check", []github.CheckRun{
			run(1, "build", "completed", "success", "mallory-ci"), run(2, "test", "completed", "success", "mallory-ci"),
		}, false, false},
		{"another App cannot fail one either", []github.CheckRun{
			run(1, "build", "completed", "success", gha), run(2, "test", "completed", "success", gha), run(9, "build", "completed", "failure", "mallory-ci"),
		}, true, true},
		{"an unrequired check is ignored", []github.CheckRun{
			run(1, "build", "completed", "success", gha), run(2, "test", "completed", "success", gha), run(3, "lint", "completed", "failure", gha),
		}, true, true},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			res, checks := evaluateChecks(p, tc.runs)
			if res.Completed != tc.completed || res.Passed != tc.pass {
				t.Fatalf("evaluateChecks = %+v, want completed %t passed %t", res, tc.completed, tc.pass)
			}
			if len(checks) != len(p.RequiredChecks) {
				t.Fatalf("%d checks recorded, want one per required check", len(checks))
			}
		})
	}
}

// TestCommitMessage: the subject, the body, and the platform's four
// trailers, the same bytes every time for the same inputs.
func TestCommitMessage(t *testing.T) {
	out := agent.PRWriterOutput{Type: "fix", Scope: "tally", Description: "count blank ballots", Body: "Blank ballots were dropped."}
	meta := commitMeta{FinishedAt: time.Date(2026, 10, 31, 12, 0, 0, 0, time.UTC), Model: "claude-fable-5-1", PlanVersion: 2}
	got := commitMessage(out, "task-id", "plan-id", meta)
	want := "fix(tally): count blank ballots\n\nBlank ballots were dropped.\n\n" +
		"Task: task-id\nPlan: plan-id v2\nModel: claude-fable-5-1\nGenerated-by: conclave\n"
	if got != want {
		t.Fatalf("commitMessage =\n%q\nwant\n%q", got, want)
	}
	if again := commitMessage(out, "task-id", "plan-id", meta); again != got {
		t.Fatal("commitMessage is not deterministic")
	}
	out.Body = ""
	if got := commitMessage(out, "t", "p", meta); !strings.HasPrefix(got, "fix(tally): count blank ballots\n\nTask: t\n") {
		t.Fatalf("no-body message = %q", got)
	}
}

// TestRenderPullRequestBody: the AI label comes first, then the security
// section naming every flagged gate before the model's prose; the gate
// evidence names the pushed artifact, and the body closes the issue.
func TestRenderPullRequestBody(t *testing.T) {
	results := []contracts.GateResult{
		{Gate: contracts.GateBuild, Passed: true, Mode: contracts.GatingCleanRoom},
		{Gate: contracts.GateExecSurface, Passed: true, Flagged: true, Detail: "changed Makefile | build.gradle", Mode: contracts.GatingCleanRoom},
	}
	pr := store.PullRequestRecord{Summary: "Adds export.", Risks: "None.", RebasedArtifactHash: strings.Repeat("c", 64),
		OriginalBaseSHA: strings.Repeat("a", 40), BaseSHA: strings.Repeat("b", 40)}
	body := renderPullRequestBody(pullRequestView{Issue: 7, PlanID: "plan-id", PlanVersion: 1, PR: pr, Results: results})
	order := []string{"generated by Conclave", "## Security-relevant changes", "**execution_surface**: changed Makefile \\| build.gradle",
		"## Summary", "## Risks", "## Gate evidence", pr.RebasedArtifactHash, "## Plan", "Closes #7"}
	at := 0
	for _, want := range order {
		i := strings.Index(body[at:], want)
		if i < 0 {
			t.Fatalf("body lacks %q after offset %d:\n%s", want, at, body)
		}
		at += i
	}
	quiet := renderPullRequestBody(pullRequestView{Issue: 7, PR: pr, Results: results[:1]})
	if !strings.Contains(quiet, "No gate flagged a security-relevant change.") {
		t.Fatalf("body without flags:\n%s", quiet)
	}
}
