// Package store provides Postgres access: the goose migrations that define
// the schema, embedded so a binary can apply them, and the compare-and-set
// helpers every state change goes through.
//
// State changes use UPDATE ... WHERE state = expected AND revision =
// expected (RL-13). Legality of a move is decided by the transition table in
// package contracts before any SQL runs. The audit row in state_transitions
// is written by a database trigger that fires on any change to a state
// column and refuses the change when no actor has been set on the
// transaction, so the audit trail (FR-SEC10) holds for every database role
// short of the table owner, whether or not the change went through the
// helpers. The actor string is self-reported; the trigger also records the
// authenticated login as db_user. Cost events and state transitions are
// append-only: the application role has insert-only access to them.
// CostLedger is the router's ledger over cost_events and
// budget_reservations: it checks a scope's attribution, reserves each model
// call against the FR-SEC9 caps under one transaction-level advisory lock,
// and settles the call by recording its event and deleting its reservation
// in one transaction. A replayed event is absorbed by the idempotency key
// rather than rejected. RepoDirectory gives the
// router each repository's record, which it checks against the owner's
// configured tier. ToolCalls is the agent's audit recorder over the
// append-only tool_calls table (FR-SEC24).
//
// The work-table functions create the rows a run hangs off: EnsureRepo
// makes a repository's row match the owner's configuration, and
// CreateFeatureRequest, CreatePlan, CreateTask and CreateAttempt insert a
// record in its initial state. Each is idempotent on the table's natural
// key (RL-2): a repeated call returns the existing row, reports that it
// did not create it, and overwrites nothing. Like Transition, they need
// READ COMMITTED, Postgres's default: on a conflict they read the existing
// row back in a new statement, which sees a row another transaction has
// just committed only under that level. Under REPEATABLE READ the read
// misses it and the create reports the parent as not found. Inserting a
// row is not a transition and writes no audit row. The attempt's cleanup columns are
// written through SetAttemptSandbox, before any agent step, and
// MarkSandboxReleased, and UnreleasedAttempts lists the sandboxes the
// reaper must still release (RL-3). SetArtifactHash records the frozen
// artifact once, and FinishAttempt moves an attempt to its terminal state
// and records its usage and report in the same transaction. Every input
// these functions can check is checked before any SQL runs, so a refusal
// leaves the caller's transaction usable. ActorWorkflow, ActorGitHub and
// ActorWorker are the actor strings for the audit trigger.
//
// These grants are a control only when the application connects as a
// non-owner LOGIN role that is a member of conclave_app. SET ROLE
// conclave_app is acceptable from such a role, never from the owner: a
// connection that logged in as the owner can RESET ROLE and every grant
// evaporates. The package's tests use SET LOCAL ROLE from the owner pool as
// a stand-in for that deployment shape, which exercises the grants but not
// the login.
//
// Typed queries for the rest of the schema are generated by sqlc from visible
// SQL as later tickets need them.
